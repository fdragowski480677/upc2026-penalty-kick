def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*")
    a = ap.parse_args()
    for name, f in FIGURES.items():
        if a.only and name not in a.only:
            continue
        try:
            f()
        except FileNotFoundError as e:
            print(f"skip {name}: {e}")


if __name__ == "__main__":
    main()
