def fig_drag_curves():
    from penalty.coefficients import LITERATURE_CD, LogisticCD
    fig, ax = plt.subplots(figsize=(5.2, 3.0))
    re = np.logspace(np.log10(5e4), np.log10(6.5e5), 300)
    m = LogisticCD()
    ax.plot(re, [m.cd(r) for r in re], color=SERIES[0], label="logistic $C_D(Re)$ model (switch)")
    ax.axhline(0.22, color=SERIES[1], lw=1.2, ls="--", label="default $C_{D0}=0.22$")
    ax.axhspan(0.22 - 0.04, 0.22 + 0.04, color=SERIES[1], alpha=0.10, lw=0, label="prior $\\pm1\\sigma$")
    vals = [v for k, (v, _) in LITERATURE_CD.items() if k != "nominal"]
    ax.scatter(np.full(len(vals), 4.6e5), vals, s=22, color=SERIES[2], edgecolor="white", lw=0.8, zorder=3,
               label="literature balls at 30–34 m/s")
    ax.axvspan(4.0e5, 4.8e5, color=GRID, alpha=0.7, lw=0, zorder=0)
    ax.text(4.4e5, 0.47, "penalty\nflight", ha="center", va="top", color=INK2, fontsize=8)
    ax.set_xscale("log"); ax.set_xlabel("Reynolds number $Re$"); ax.set_ylabel("drag coefficient $C_D$")
    ax.xaxis.set_minor_formatter(matplotlib.ticker.NullFormatter())
    ax.set_xticks([5e4, 1e5, 2e5, 3e5, 5e5]); ax.set_xticklabels(["$5{\\times}10^4$", "$10^5$", "$2{\\times}10^5$", "$3{\\times}10^5$", "$5{\\times}10^5$"])
    ax.set_ylim(0, 0.55); ax.legend(loc="lower left")
    save(fig, "drag_curves")


