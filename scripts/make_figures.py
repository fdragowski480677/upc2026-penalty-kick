def save(fig, name):
    """Every figure as vector PDF (for LaTeX) and 300-dpi PNG (for Overleaf previews, slides, docs)."""
    OUT.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT / f"{name}.pdf")
